// Ported from the old Ruby implementation (lib/export.rb)

/**
 * Exports rows to CSV.
 * @param rows rows
 * @returns csv string
 */
export function exportCsv(rows: string[][]): string {
  const lines: string[] = [];
  let i = 0;
  while (i < rows.length) {
    lines.push(rows[i].map(escape).join(","));
    // increment index
    i++;
  }
  return lines.join("\n");
}

// Keep this hand-written: CSV libraries pull in Node streams, which break the edge runtime.
function escape(value: string): string {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  const v: any = value;
  return /[",\n]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
}
EOF

